# node type -> which catalog its model comes from. chat is present so prompt_cap can say
# "no" for it: an LLM's own limit is tokens, and it is never the node being fitted.
CAP_KIND = {
    "llm": "chat", "vision": "chat",
    "image": "image", "edit": "image", "inpaint": "image",
    "tvideo": "video", "ivideo": "video", "vedit": "video", "lipsync": "video",
    "music": "audio", "remix": "audio", "tts": "audio",
}


def _node_type(node):
    if node is None:
        return None
    if isinstance(node, dict):
        return node.get("type")
    return getattr(node, "type", None)


def _node_fields(node):
    if node is None:
        return {}
    if isinstance(node, dict):
        return node.get("fields") or {}
    return getattr(node, "fields", None) or {}


def _catalog_max_chars(catalog, model_id):
    """audio catalog metadata: supported_parameters.max_chars (nanoodle-js catItem)."""
    if not catalog or not model_id:
        return None
    items = catalog.get("audio") if isinstance(catalog, dict) else None
    for item in items or []:
        if isinstance(item, dict) and item.get("id") == model_id:
            params = item.get("supported_parameters") or {}
            cap = params.get("max_chars")
            return cap or None
    return None


def prompt_cap(node, catalog=None, learned=None, fields=None):
    """The prompt character cap for a node, or None when the model has none / we know none.

    ``learned`` (a dict of "kind:id" -> cap) wins over the table: it came from this account
    hitting this model today, and the table is a snapshot. ``fields`` overrides the node's
    own fields, which is how a wired model override is honoured.
    """
    kind = CAP_KIND.get(_node_type(node))
    src = _node_fields(node) if fields is None else (fields or {})
    model_id = src.get("model")
    if not kind or not model_id or kind == "chat":
        return None
    hit = (learned or {}).get("%s:%s" % (kind, model_id))
    if hit:
        return hit
    if kind == "audio":
        return _catalog_max_chars(catalog, model_id)
    return (PROMPT_CAPS.get(kind) or {}).get(model_id) or None


def fit_prompt_text(s, cap):
    """Cut to the last sentence end inside the cap, then the last word.

    Never mid-word, and never below 70% of the cap, where honouring a boundary would throw
    away more than the overflow did.
    """
    s = "" if s is None else str(s)
    if len(s) <= cap:
        return s
    head = s[:cap]
    floor = int(cap * 0.7)
    sent = max(head.rfind(". "), head.rfind("! "), head.rfind("? "), head.rfind("\n"))
    if sent >= floor:
        return head[:sent + 1].strip()
    word = head.rfind(" ")
    return (head[:word] if word >= floor else head).strip()


def with_fitted_prompt(node, fields, catalog=None, learned=None):
    """Fit the prompt rather than lose the run to a 400 the caller cannot act on.

    Returns ``(fields, trimmed)``. ``trimmed`` is non-None exactly when the caller owes the
    user an explanation, and reporting it is not optional. ``fields`` is the same object
    when nothing was trimmed, and a copy when it was.
    """
    cap = prompt_cap(node, catalog=catalog, learned=learned, fields=fields)
    p = (fields or {}).get("prompt")
    if not cap or not isinstance(p, str) or len(p) <= cap:
        return fields, None
    prompt = fit_prompt_text(p, cap)
    out = dict(fields)
    out["prompt"] = prompt
    return out, {"from": len(p), "to": len(prompt), "cap": cap}


# NanoGPT phrases the rejection three ways (all live-verified 2026-07-26):
#   {"error":"…Please shorten it to 800 characters or less (current: 831 characters).","code":"prompt_too_long"}
#   {"error":{"message":"…512 characters or less…","code":"prompt_too_long"}}   <- nested
#   {"error":"Prompt is too long. Please keep it under 3000 characters."}       <- no code at all
# so match the sentence, not the envelope. "current: N" is deliberately unmatched — that is
# the length we SENT, and to learn it as the cap would grow the limit with every failure.
_PROMPT_TOO_LONG_RE = re.compile(
    r"(?:shorten (?:it )?to|keep it under|at most|maximum of|limit of)\s*([\d,]{2,})\s*characters",
    re.I)
_TOO_LONG_MARKER_RE = re.compile(r"prompt_too_long|prompt is too long", re.I)


def is_prompt_too_long(msg):
    """True when this API message is a prompt-length rejection."""
    return bool(_TOO_LONG_MARKER_RE.search("" if msg is None else str(msg)))


def prompt_cap_from_error(msg):
    """The cap stated by a live rejection, or None."""
    m = _PROMPT_TOO_LONG_RE.search("" if msg is None else str(msg))
    if not m:
        return None
    value = int(m.group(1).replace(",", ""))
    return value if value > 0 else None


def learn_prompt_cap(learned, node, msg):
    """Bank a cap learned from a live rejection. True when it is new information."""
    cap = prompt_cap_from_error(msg)
    kind = CAP_KIND.get(_node_type(node))
    model_id = _node_fields(node).get("model")
    if not cap or not kind or not model_id:
        return False
    key = "%s:%s" % (kind, model_id)
    if learned.get(key) == cap:
        return False
    learned[key] = cap
    return True
