"""Prompt length caps — the wired prompt nobody can shorten.

Port of nanoodle-js src/prompt-caps.mjs. Keep the two in step.

Many image and video models reject an over-long prompt at NanoGPT's route, before the
provider is called and before anything is charged::

    400 {"error":"Your prompt is too long for Qwen Image 3. Please shorten it to 800
         characters or less (current: 831 characters).","code":"prompt_too_long"}

Free, but a dead end. In a graph the prompt is generated, not typed — an LLM node writes
it and a wire carries it into the image node — so "please shorten it" names something no
caller controls directly. For a headless or agent-driven run that is the whole workflow
lost to a limit nobody was told about.

So: trim it to fit at a sentence boundary (``fit_prompt_text``) and REPORT it — a
``prompt-trimmed`` progress event plus a Python warning. A silent trim would be a bug; the
report is what makes the trim defensible. A cap we did not know is learned from the live
400 (``prompt_cap_from_error``) and kept on the Workflow, so a retry states the limit
instead of rediscovering it.

What this deliberately does NOT do is edit the graph's own prompts to avoid the trim. An
llm node's system prompt goes to the model exactly as its author wrote it. To inject a
"keep it under N characters" directive on their behalf would silently change what their
workflow produces.

The image/video catalogs advertise no prompt limit at all (checked live 2026-07-26), hence
the probed table below. Audio caps ARE catalog metadata (supported_parameters.max_chars)
and are read from the opt-in catalog instead — never listed here. An absent id means no cap
found, or never probed: unknown stays unconstrained, which matches this library's
permissive-gate rule everywhere else.

Table generated by nanoodle's scripts/probe-prompt-caps.mjs. Keep it in step with the
copies in nanoodle-js, and in nanoodle's index.html / play.html.
"""

